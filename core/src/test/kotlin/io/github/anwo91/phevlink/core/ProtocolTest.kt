package io.github.anwo91.phevlink.core

import io.github.anwo91.phevlink.core.protocol.Codec
import io.github.anwo91.phevlink.core.protocol.Packet
import io.github.anwo91.phevlink.core.protocol.PacketType
import io.github.anwo91.phevlink.core.protocol.SecurityKey
import io.github.anwo91.phevlink.core.protocol.StreamDecoder
import io.github.anwo91.phevlink.core.protocol.hexToBytes
import io.github.anwo91.phevlink.core.protocol.toHex
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class ProtocolTest {

    @Test
    fun checksumMatchesDocumentedExample() {
        // From the protocol notes: f3040020 sums to 0x117 -> checksum 0x17.
        assertEquals(0x17, Codec.checksum("f3040020".hexToBytes(), 4))
        val ping = Packet(PacketType.PING_REQ, 0, 0x20, ByteArray(0))
        assertEquals("f303002016", ping.toPlainBytes().toHex())
    }

    @Test
    fun encodeAndDecodeRoundTripWithXor() {
        val p = Packet(PacketType.RESP, 0, 0x1d, byteArrayOf(64, 0, 1, 0))
        for (xor in listOf(0, 0x01, 0x5a, 0xff)) {
            val wire = p.encode(xor)
            val items = StreamDecoder().feed(wire)
            assertEquals(1, items.size)
            val d = items[0] as StreamDecoder.Item.Decoded
            assertEquals(p, d.packet)
            assertEquals(xor, d.xor)
        }
    }

    /** Vectors generated by phev2mqtt's Go implementation (protocol/raw.go + message.go). */
    @Test
    fun securityKeyMatchesReferenceImplementation() {
        data class Vec(val seed: String, val keys: String, val write: String, val ping: String, val ack: String)
        val vectors = listOf(
            Vec("4e0d0001a1b2c3d4e5f60718010000", "803d8354ebd0", "7684808a8185", "ce393d373d3c", "cb393c203d25"),
            Vec("5e0c000112345678deadbeef01", "f017ebe6e22b", "06f4f0faf1f5", "e413171d1716", "e113160a170f"),
            Vec("4e0d000100ffff00ff00ff0001aa00", "42ad055e2274", "b44642484347", "5ea9ada7adac", "5ba9acb0adb5"),
        )
        for (v in vectors) {
            val k = SecurityKey().apply { update(v.seed.hexToBytes()) }
            val keys = ByteArray(6) { k.sendKey(advance = true).toByte() }
            assertEquals("keys for ${v.seed}", v.keys, keys.toHex())

            val k2 = SecurityKey().apply { update(v.seed.hexToBytes()) }
            val write = Packet(PacketType.SEND, 0, 0x0a, byteArrayOf(1)).encode(k2.sendKey(advance = true))
            assertEquals(v.write, write.toHex())
            val ping = Packet(PacketType.PING_REQ, 0, 0x0a, byteArrayOf(0)).encode(k2.sendKey(advance = false))
            assertEquals(v.ping, ping.toHex())
            val ack = Packet(PacketType.SEND, 1, 0x1d, byteArrayOf(0)).encode(k2.sendKey(advance = true))
            assertEquals(v.ack, ack.toHex())
        }
    }

    @Test
    fun resyncPointsSendIndexAtExpectedKey() {
        val k = SecurityKey().apply { update("4e0d0001a1b2c3d4e5f60718010000".hexToBytes()) }
        val map = k.keyMap!!
        repeat(5) { k.sendKey(advance = true) }
        assertTrue(k.resyncSend(map[42]))
        assertEquals(map[42], k.sendKey(advance = true))
        assertEquals(map[43], k.sendKey(advance = false))
    }

    @Test
    fun resyncWithoutKeyMapForcesNextKey() {
        val k = SecurityKey()
        assertFalse(k.resyncSend(0x77))
        assertEquals(0x77, k.sendKey(advance = true))
        assertEquals(0, k.sendKey(advance = true))
    }

    @Test
    fun decoderReassemblesFragmentedAndMergedPackets() {
        val a = Packet(PacketType.RESP, 0, 0x1d, byteArrayOf(64, 0, 1, 0)).encode(0x33)
        val b = Packet(PacketType.PING_RESP, 1, 0x0b, byteArrayOf(0)).encode(0x33)
        val c = Packet(PacketType.RESP, 0, 0x24, ByteArray(10)).encode(0x8c)
        val stream = a + b + c
        val dec = StreamDecoder()
        val out = mutableListOf<StreamDecoder.Item>()
        // feed one byte at a time
        for (byte in stream) out += dec.feed(byteArrayOf(byte))
        val packets = out.filterIsInstance<StreamDecoder.Item.Decoded>().map { it.packet.register }
        assertEquals(listOf(0x1d, 0x0b, 0x24), packets)
        assertEquals(0, dec.buffered)
        // all at once
        val all = StreamDecoder().feed(stream).filterIsInstance<StreamDecoder.Item.Decoded>()
        assertEquals(3, all.size)
    }

    @Test
    fun decoderSkipsGarbageAndResyncs() {
        val good = Packet(PacketType.RESP, 0, 0x1f, byteArrayOf(1, 30, 0)).encode(0x10)
        val items = StreamDecoder().feed(byteArrayOf(0x55, 0x12, 0x77) + good)
        val garbage = items.filterIsInstance<StreamDecoder.Item.Garbage>().sumOf { it.bytes.size }
        val decoded = items.filterIsInstance<StreamDecoder.Item.Decoded>()
        assertEquals(1, decoded.size)
        assertEquals(0x1f, decoded[0].packet.register)
        assertTrue(garbage in 1..3)
    }

    @Test
    fun staleFlushUnblocksCorruptLengthByte() {
        val dec = StreamDecoder()
        // A head byte whose length field claims a long packet that never completes.
        assertTrue(dec.feed(byteArrayOf(0x6f, 0x60, 0x00, 0x1d, 0x01)).isEmpty())
        assertTrue(dec.buffered > 0)
        // A valid packet arriving behind it is found by look-ahead, no waiting needed.
        val good = Packet(PacketType.PING_RESP, 1, 1, byteArrayOf(0)).encode(0)
        val items = dec.feed(good)
        assertTrue(items.any { it is StreamDecoder.Item.Decoded })
        assertTrue(items.any { it is StreamDecoder.Item.Garbage })
        // A stale partial head on its own is discarded by flushStale.
        val dec2 = StreamDecoder()
        dec2.feed(byteArrayOf(0x6f, 0x60, 0x00, 0x1d, 0x01, 0x02))
        val flushed = dec2.flushStale()
        assertTrue(flushed.any { it is StreamDecoder.Item.Garbage })
    }

    @Test
    fun responseTypeIsNibbleSwap() {
        assertEquals(PacketType.START_RESP_MY14, PacketType.responseFor(PacketType.START_REQ_MY14))
        assertEquals(PacketType.START_RESP_MY18, PacketType.responseFor(PacketType.START_REQ_MY18))
        assertEquals(PacketType.SEND, PacketType.responseFor(PacketType.RESP))
        assertArrayEquals("e404010100ea".hexToBytes(), Packet(0xe4, 1, 1, byteArrayOf(0)).toPlainBytes())
    }
}
